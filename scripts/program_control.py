def detect_cycles(graph: dict[str, list[str]]) -> list[list[str]]:
    cycles: list[list[str]] = []
    visited: set[str] = set()
    active: set[str] = set()
    stack: list[str] = []

    def visit(node: str) -> None:
        if node in active:
            start = stack.index(node)
            cycle = stack[start:] + [node]
            if cycle not in cycles:
                cycles.append(cycle)
            return
        if node in visited:
            return
        active.add(node)
        stack.append(node)
        for dependency in graph.get(node, []):
            if dependency in graph:
                visit(dependency)
        stack.pop()
        active.remove(node)
        visited.add(node)

    for node in graph:
        visit(node)
    return cycles


def git_output(repo_path: Path, *args: str) -> tuple[int, str]:
    result = subprocess.run(
        ["git", "-c", "core.quotepath=false", "-C", str(repo_path), *args],
        check=False,
        capture_output=True,
        text=True,
    )
    return result.returncode, result.stdout.rstrip("\n")


def parse_dirty_paths(output: str) -> list[str]:
    paths: list[str] = []
    if "\0" in output:
        records = iter(output.split("\0"))
        for record in records:
            if len(record) < 4:
                continue
            paths.append(record[3:].rstrip("/"))
            if "R" in record[:2] or "C" in record[:2]:
                original = next(records, "")
                if original:
                    paths.append(original.rstrip("/"))
        return paths
    for line in output.splitlines():
        if len(line) < 4:
            continue
        path = line[3:]
        if " -> " in path:
            path = path.split(" -> ", maxsplit=1)[1]
        paths.append(path.rstrip("/"))
    return paths


def markdown_sections(content: str, heading_prefix: str) -> list[list[str]]:
    """Return all matching H2/H3 bodies, ignoring headings/items in fences."""
    lines = content.splitlines()
    headings: list[tuple[int, int, str]] = []
    fence_character: str | None = None
    for index, line in enumerate(lines):
        fence = FENCE_PATTERN.match(line)
        if fence:
            current_character = fence.group(1)[0]
            if fence_character is None:
                fence_character = current_character
            elif fence_character == current_character:
                fence_character = None
            continue
        if fence_character is not None:
            continue
        heading = HEADING_PATTERN.match(line)
        if heading:
            headings.append((index, len(heading.group(1)), heading.group(2)))

    selected = [
        heading for heading in headings if heading[2].startswith(heading_prefix)
    ]
    bodies: list[list[str]] = []
    for start_index, level, _ in selected:
        end = len(lines)
        for index, candidate_level, _ in headings:
            if index > start_index and candidate_level <= level:
                end = index
                break

        body: list[str] = []
        fence_character = None
        for line in lines[start_index + 1 : end]:
            fence = FENCE_PATTERN.match(line)
            if fence:
                current_character = fence.group(1)[0]
                if fence_character is None:
                    fence_character = current_character
                elif fence_character == current_character:
                    fence_character = None
                continue
            if fence_character is None and HEADING_PATTERN.match(line) is None:
                body.append(line)
        bodies.append(body)
    return bodies


def markdown_section(content: str, heading_prefix: str) -> list[str] | None:
    sections = markdown_sections(content, heading_prefix)
    return sections[0] if sections else None


def markdown_task_matches(content: str) -> list[re.Match[str] | None]:
    """Return checkbox matches outside fenced examples."""
    matches: list[re.Match[str] | None] = []
    fence_character: str | None = None
    for line in content.splitlines():
        fence = FENCE_PATTERN.match(line)
        if fence:
            current_character = fence.group(1)[0]
            if fence_character is None:
                fence_character = current_character
            elif fence_character == current_character:
                fence_character = None
            continue
        if fence_character is None and TASK_PREFIX_PATTERN.match(line):
            matches.append(CHECKBOX_PATTERN.match(line))
    return matches


def markdown_heading_count(content: str) -> int:
    """Count real Markdown headings outside fenced command output."""
    count = 0
    fence_character: str | None = None
    for line in content.splitlines():
        fence = FENCE_PATTERN.match(line)
        if fence:
            current_character = fence.group(1)[0]
            if fence_character is None:
                fence_character = current_character
            elif fence_character == current_character:
                fence_character = None
            continue
        if fence_character is None and re.match(r"^#{1,6}\s+\S", line):
            count += 1
    return count


def has_recorded_command(content: str) -> bool:
    """Require one recognizable command in inline or shell-fenced code."""
    for inline in INLINE_CODE_PATTERN.findall(content):
        if COMMAND_PREFIX_PATTERN.match(inline.strip()):
            return True

    fence_character: str | None = None
    shell_fence = False
    for line in content.splitlines():
        fence = FENCE_PATTERN.match(line)
        if fence:
            current_character = fence.group(1)[0]
            if fence_character is None:
                fence_character = current_character
                info = line[fence.end(1) :].strip().lower()
                shell_fence = info in {"sh", "bash", "zsh", "shell", "console"}
            elif fence_character == current_character:
                fence_character = None
                shell_fence = False
            continue
        if shell_fence and COMMAND_PREFIX_PATTERN.match(line.strip()):
            return True
    return False


def has_meaningful_markdown_content(lines: list[str]) -> bool:
    return any(
        WORD_PATTERN.search(line) is not None
        and HTML_COMMENT_PATTERN.match(line) is None
        for line in lines
    )


def inline_metadata(content: str) -> dict[str, list[str]]:
    """Collect inline-code metadata fields without hiding duplicate labels."""
    metadata: dict[str, list[str]] = {}
    for label, value in INLINE_METADATA_PATTERN.findall(content):
        metadata.setdefault(label.strip(), []).append(value.strip())
    return metadata


def is_placeholder(value: str) -> bool:
    normalized = value.strip()
    return (
        normalized.upper() in PLACEHOLDER_VALUES
        or (normalized.startswith("<") and normalized.endswith(">"))
    )


def validate_adr005_acceptance(
    program: dict[str, Any], root: Path = ROOT
) -> list[Issue]:
    """Fail closed when ADR-005 acceptance metadata and card state diverge."""
    cards = program.get("cards", [])
    card = next(
        (
            item
            for item in cards
            if isinstance(item, dict) and item.get("id") == ADR005_CARD_ID
        ),
        None,
    )
    # Small unit fixtures and historical program schemas may not contain ADR-005.
    if card is None:
        return []

    issues: list[Issue] = []
    record_path = root / "program" / "decisions" / "ADR-005-acceptance.md"
    adr_path = root / "program" / "decisions" / "ADR-005-trip-scoped-location-access.md"
    try:
        record = record_path.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as error:
        return [
            Issue(
                "ERROR",
                "ADR005_ACCEPTANCE_RECORD",
                f"registro de aceite ADR-005 ausente ou ilegível: {error}",
            )
        ]
    try:
        adr_bytes = adr_path.read_bytes()
        adr = adr_bytes.decode("utf-8")
        adr_digest = hashlib.sha256(adr_bytes).hexdigest()
    except (OSError, UnicodeError) as error:
        return [
            Issue(
                "ERROR",
                "ADR005_FROZEN_REVISION",
                f"ADR-005 congelada ausente ou ilegível: {error}",
            )
        ]

    for marker in (ADR005_REVISION, ADR005_DIGEST):
        if marker not in record:
            issues.append(
                Issue(
                    "ERROR",
                    "ADR005_ACCEPTANCE_REVISION",
                    f"registro de aceite não referencia {marker}",
                )
            )
    if f"coordination:{ADR005_REVISION}" not in card.get("commits", []):
        issues.append(
            Issue(
                "ERROR",
                "ADR005_ACCEPTANCE_REVISION",
                "card não referencia o commit congelado da ADR-005",
            )
        )

    metadata = inline_metadata(record)

    def single_value(label: str) -> str | None:
        values = metadata.get(label, [])
        if len(values) != 1:
            issues.append(
                Issue(
                    "ERROR",
                    "ADR005_ACCEPTANCE_METADATA",
                    f"registro deve conter exatamente um campo `{label}`; "
                    f"encontrado(s) {len(values)}",
                )
            )
            return None
        return values[0]

    status_value = single_value("status")
    verdict_value = single_value("veredito")
    field_values = {label: single_value(label) for label in ADR005_ACCEPTANCE_FIELDS}
    card_status = card.get("status")

    binding = (ADR005_REVISION, ADR005_DIGEST)
    binding_is_superseded = binding in ADR005_SUPERSEDED_BINDINGS
    record_is_superseded = (
        status_value == ADR005_SUPERSEDED_STATUS
        and verdict_value == ADR005_SUPERSEDED_STATUS
    )
    if binding_is_superseded:
        if (
            status_value != ADR005_SUPERSEDED_STATUS
            or verdict_value != ADR005_SUPERSEDED_STATUS
        ):
            issues.append(
                Issue(
                    "ERROR",
                    "ADR005_SUPERSEDED_REVISION",
                    "revisão revogada permanentemente exige tombstone; "
                    "não pode retornar a WAITING_HUMAN ou ACCEPTED",
                )
            )
        if card_status != ADR005_REFREEZE_CARD_STATUS:
            issues.append(
                Issue(
                    "ERROR",
                    "ADR005_ACCEPTANCE_STATE",
                    "registro superseded exige card analyzed para novo freeze",
                )
            )
        if adr_digest == ADR005_DIGEST:
            issues.append(
                Issue(
                    "ERROR",
                    "ADR005_FROZEN_REVISION",
                    "revisão histórica superseded ainda é a ADR operacional atual",
                )
            )
        adr_status_values = inline_metadata(adr).get("status", [])
        if adr_status_values != [ADR005_REFREEZE_ADR_STATUS]:
            issues.append(
                Issue(
                    "ERROR",
                    "ADR005_REFREEZE_STATUS",
                    "ADR operacional deve declarar exatamente o status "
                    f"{ADR005_REFREEZE_ADR_STATUS}",
                )
            )
        missing_refreeze_markers = [
            marker
            for marker in (
                ADR005_SUPERSEDED_STATUS,
                "REFREEZE_REQUIRED",
                "NOT_ACCEPTED",
            )
            if marker not in adr
        ]
        if missing_refreeze_markers:
            issues.append(
                Issue(
                    "ERROR",
                    "ADR005_REFREEZE_REQUIRED",
                    "ADR operacional não declara fail-closed de refreeze: "
                    + ", ".join(missing_refreeze_markers),
                )
            )
        premature_flyway_versions = sorted(
            {
                int(match.group(1))
                for match in ADR005_FLYWAY_VERSION_PATTERN.finditer(adr)
                if int(match.group(1)) > ADR005_MAX_EXISTING_FLYWAY
            }
        )
        if premature_flyway_versions:
            issues.append(
                Issue(
                    "ERROR",
                    "ADR005_PREMATURE_FLYWAY",
                    "ADR analyzed reserva Flyway futuro: "
                    + ", ".join(
                        f"V{version}" for version in premature_flyway_versions
                    ),
                )
            )
        for label, value in field_values.items():
            if value is not None and value != "INVALIDATED":
                issues.append(
                    Issue(
                        "ERROR",
                        "ADR005_SUPERSEDED_METADATA",
                        f"{label} deve registrar INVALIDATED no tombstone",
                    )
                )
        blockers = card.get("blockers", [])
        blocker_text = "\n".join(blockers) if isinstance(blockers, list) else ""
        required_blocker_fragments = (
            "SUPERSEDED/DO_NOT_ACCEPT",
            "Flyway",
            "waiting_human",
        )
        if any(
            fragment not in blocker_text
            for fragment in required_blocker_fragments
        ):
            issues.append(
                Issue(
                    "ERROR",
                    "ADR005_ACCEPTANCE_STATE",
                    "card analyzed deve explicar supersession, Flyway e novo waiting_human",
                )
            )
        return issues

    if record_is_superseded:
        issues.append(
            Issue(
                "ERROR",
                "ADR005_SUPERSEDED_REVISION",
                "tombstone exige binding explicitamente revogado no ratchet",
            )
        )
        return issues

    if adr_digest != ADR005_DIGEST:
        issues.append(
            Issue(
                "ERROR",
                "ADR005_FROZEN_REVISION",
                f"SHA-256 da ADR-005 diverge: {adr_digest}",
            )
        )
    missing_declarations = [
        fragment for fragment in ADR005_DECLARATION_FRAGMENTS if fragment not in record
    ]
    if missing_declarations:
        issues.append(
            Issue(
                "ERROR",
                "ADR005_ACCEPTANCE_DECLARATIONS",
                "registro perdeu declaração(ões) obrigatória(s): "
                + ", ".join(missing_declarations),
            )
        )

    if card_status == "waiting_human":
        if status_value != "WAITING_HUMAN" or verdict_value != "WAITING_HUMAN":
            issues.append(
                Issue(
                    "ERROR",
                    "ADR005_ACCEPTANCE_STATE",
                    "card waiting_human exige status e veredito WAITING_HUMAN",
                )
            )
        for label, value in field_values.items():
            if value is not None and value != "PENDING":
                issues.append(
                    Issue(
                        "ERROR",
                        "ADR005_ACCEPTANCE_PENDING",
                        f"{label} deve permanecer PENDING antes do aceite",
                    )
                )
        blockers = card.get("blockers", [])
        blocker_text = "\n".join(blockers) if isinstance(blockers, list) else ""
        if ADR005_REVISION not in blocker_text or ADR005_DIGEST not in blocker_text:
            issues.append(
                Issue(
                    "ERROR",
                    "ADR005_ACCEPTANCE_STATE",
                    "blocker waiting_human deve identificar revisão e digest congelados",
                )
            )
        return issues

    if card_status not in ADR005_POST_ACCEPTANCE_STATUSES:
        issues.append(
            Issue(
                "ERROR",
                "ADR005_ACCEPTANCE_STATE",
                f"estado {card_status} não representa espera nem pós-aceite ADR-005",
            )
        )
        return issues

    if status_value != "ACCEPTED" or verdict_value != "ACCEPTED":
        issues.append(
            Issue(
                "ERROR",
                "ADR005_ACCEPTANCE_STATE",
                "estado pós-aceite exige status e veredito ACCEPTED",
            )
        )
    for label, value in field_values.items():
        if value is not None and is_placeholder(value):
            issues.append(
                Issue(
                    "ERROR",
                    "ADR005_ACCEPTANCE_METADATA",
                    f"campo `{label}` está vazio ou usa placeholder",
                )
            )

    phrase = field_values["frase recebida"]
    if phrase is not None:
        required_phrase_fragments = (
            "Aceito a recomendação completa da ADR-005",
            ADR005_REVISION,
            ADR005_DIGEST,
            "Declaro ciência das declarações obrigatórias deste registro",
            "não concede GO a piloto ou produção",
        )
        identity_fragments = tuple(
            value
            for label in (
                "aprovador de Produto",
                "autoridade de Produto",
                "aprovador de Privacidade",
                "autoridade de Privacidade",
            )
            if (value := field_values[label]) is not None
            and not is_placeholder(value)
        )
        if any(fragment not in phrase for fragment in required_phrase_fragments):
            issues.append(
                Issue(
                    "ERROR",
                    "ADR005_ACCEPTANCE_PHRASE",
                    "frase recebida não identifica aceite integral, revisão e digest",
                )
            )
        if any(fragment not in phrase for fragment in identity_fragments):
            issues.append(
                Issue(
                    "ERROR",
                    "ADR005_ACCEPTANCE_PHRASE",
                    "frase recebida não preserva aprovadores e autoridades registrados",
                )
            )
        product_approver = field_values["aprovador de Produto"]
        privacy_approver = field_values["aprovador de Privacidade"]
        if (
            product_approver is not None
            and product_approver == privacy_approver
            and "acumula autoridade de Produto e Privacidade" not in phrase
        ):
            issues.append(
                Issue(
                    "ERROR",
                    "ADR005_ACCEPTANCE_PHRASE",
                    "um único aprovador deve declarar acúmulo das duas autoridades",
                )
            )

    timestamp = field_values["timestamp do registro"]
    if timestamp is not None and not is_placeholder(timestamp):
        if ISO_UTC_TIMESTAMP_PATTERN.fullmatch(timestamp) is None:
            issues.append(
                Issue(
                    "ERROR",
                    "ADR005_ACCEPTANCE_TIMESTAMP",
                    "timestamp do registro deve usar YYYY-MM-DDTHH:MM:SSZ",
                )
            )
        else:
            try:
                parsed_timestamp = datetime.strptime(
                    timestamp, "%Y-%m-%dT%H:%M:%SZ"
                ).replace(tzinfo=timezone.utc)
            except ValueError:
                issues.append(
                    Issue(
                        "ERROR",
                        "ADR005_ACCEPTANCE_TIMESTAMP",
                        "timestamp do registro contém data ou hora impossível",
                    )
                )
            else:
                if parsed_timestamp < ADR005_FROZEN_AT:
                    issues.append(
                        Issue(
                            "ERROR",
                            "ADR005_ACCEPTANCE_TIMESTAMP",
                            "timestamp do aceite antecede o congelamento da revisão",
                        )
                    )

    declarations = field_values["declarações obrigatórias"]
    if declarations is not None and declarations != "CIENTE":
        issues.append(
            Issue(
                "ERROR",
                "ADR005_ACCEPTANCE_DECLARATIONS",
                "declarações obrigatórias deve registrar exatamente CIENTE",
            )
        )
    if card.get("blockers"):
        issues.append(
            Issue(
                "ERROR",
                "ADR005_ACCEPTANCE_STATE",
                "card pós-aceite não pode manter blockers",
            )
        )
    return issues


def validate_static(
    program: dict[str, Any],
    repositories_doc: dict[str, Any],
    root: Path = ROOT,
    *,
    deferred_repositories: frozenset[str] = frozenset(),
) -> list[Issue]:
    issues: list[Issue] = []

    if program.get("schemaVersion") != 1:
        issues.append(Issue("ERROR", "PROGRAM_SCHEMA", "schemaVersion deve ser 1"))
    if repositories_doc.get("schemaVersion") != 1:
        issues.append(
            Issue("ERROR", "REPOSITORY_SCHEMA", "repositories schemaVersion deve ser 1")
        )

    workstreams = program.get("workstreams", [])
    milestones = program.get("milestones", [])
    epics = program.get("epics", [])
    cards = program.get("cards", [])
    repositories = repositories_doc.get("repositories", [])

    collections = {
        "workstream": workstreams,
        "milestone": milestones,
        "epic": epics,
        "card": cards,
        "repository": repositories,
    }
    ids_by_collection: dict[str, set[str]] = {}
    for label, items in collections.items():
        ids = [item.get("id") for item in items if isinstance(item, dict)]
        missing = len(items) - len([value for value in ids if value])
        if missing:
            issues.append(
                Issue("ERROR", f"{label.upper()}_ID", f"{missing} {label}(s) sem id")
            )
        string_ids = [value for value in ids if isinstance(value, str) and value]
        ids_by_collection[label] = set(string_ids)
        for duplicate in duplicates(string_ids):
            issues.append(
                Issue(
                    "ERROR",
                    f"DUPLICATE_{label.upper()}",
                    f"id duplicado em {label}: {duplicate}",
                )
            )

    all_ids: set[str] = set()
    for label, ids in ids_by_collection.items():
        overlap = all_ids.intersection(ids)
        for duplicate in sorted(overlap):
            issues.append(
                Issue(
                    "ERROR",
                    "GLOBAL_DUPLICATE_ID",
                    f"id reutilizado entre coleções: {duplicate} ({label})",
                )
            )
        all_ids.update(ids)

    workstream_ids = ids_by_collection.get("workstream", set())
    epic_ids = ids_by_collection.get("epic", set())
    repository_ids = ids_by_collection.get("repository", set())

    for item in milestones + epics + cards:
        item_id = item.get("id", "<sem-id>")
        status = item.get("status")
        if status not in CARD_STATUSES:
            issues.append(
                Issue(
                    "ERROR",
                    "INVALID_STATUS",
                    f"{item_id} usa status inválido: {status}",
                )
            )

    for epic in epics:
        epic_id = epic.get("id", "<sem-id>")
        if epic.get("workstream") not in workstream_ids:
            issues.append(
                Issue(
                    "ERROR",
                    "EPIC_WORKSTREAM",
                    f"{epic_id} referencia workstream ausente: {epic.get('workstream')}",
                )
            )

    for card in cards:
        card_id = card.get("id", "<sem-id>")
        card_content: str | None = None
        unavailable = deferred_repositories.intersection(card.get("repositories", []))
        if card.get("status") in EXECUTABLE_STATUSES and unavailable:
            issues.append(
                Issue(
                    "ERROR", "WORKSPACE_CARD_REPOSITORY",
                    f"{card_id}: trabalho executável exige módulo adiado: "
                    + ", ".join(sorted(unavailable)),
                )
            )
        if card.get("epic") not in epic_ids:
            issues.append(
                Issue(
                    "ERROR",
                    "CARD_EPIC",
                    f"{card_id} referencia epic ausente: {card.get('epic')}",
                )
            )
        for repository_id in card.get("repositories", []):
            if repository_id not in repository_ids:
                issues.append(
                    Issue(
                        "ERROR",
                        "CARD_REPOSITORY",
                        f"{card_id} referencia repositório ausente: {repository_id}",
                    )
                )

        card_file = card.get("cardFile")
        if not card_file:
            issues.append(
                Issue("ERROR", "CARD_FILE", f"{card_id} não declara cardFile")
            )
        else:
            path = root / card_file
            if not path.is_file():
                issues.append(
                    Issue(
                        "ERROR",
                        "CARD_FILE",
                        f"{card_id} aponta para arquivo ausente: {card_file}",
                    )
                )
            else:
                try:
                    card_content = path.read_text(encoding="utf-8")
                except (OSError, UnicodeError) as error:
                    issues.append(
                        Issue(
                            "ERROR",
                            "CARD_FILE_UNREADABLE",
                            f"{card_file} não pôde ser lido: {error}",
                        )
                    )
                else:
                    if card_id not in card_content:
                        issues.append(
                            Issue(
                                "ERROR",
                                "CARD_FILE_ID",
                                f"{card_file} não contém o id {card_id}",
                            )
                        )

        blockers = card.get("blockers")
        blockers_are_valid = isinstance(blockers, list) and all(
            isinstance(blocker, str) and bool(blocker.strip()) for blocker in blockers
        )
        if not blockers_are_valid:
            issues.append(
                Issue(
                    "ERROR",
                    "BLOCKER_TYPE",
                    f"{card_id}.blockers deve ser uma lista de textos não vazios",
                )
            )
        else:
            if card.get("status") in BLOCKED_STATUSES and not blockers:
                issues.append(
                    Issue(
                        "ERROR",
                        "MISSING_BLOCKER",
                        f"{card_id} está {card.get('status')} sem blocker explícito",
                    )
                )
            if card.get("status") in EXECUTABLE_STATUSES and blockers:
                issues.append(
                    Issue(
                        "ERROR",
                        "EXECUTABLE_WITH_BLOCKERS",
                        f"{card_id} está {card.get('status')} com blocker explícito",
                    )
                )

        if card.get("status") in EXECUTABLE_STATUSES and card_content is not None:
            section_occurrences = {
                heading: markdown_sections(card_content, heading)
                for heading in READY_CARD_SECTIONS
            }
            missing_sections = [
                heading
                for heading, occurrences in section_occurrences.items()
                if not occurrences
            ]
            if missing_sections:
                issues.append(
                    Issue(
                        "ERROR",
                        "EXECUTABLE_CONTRACT_SECTION",
                        f"{card_id} está {card.get('status')} sem seção(ões): "
                        + ", ".join(missing_sections),
                    )
                )
            duplicate_sections = [
                heading
                for heading, occurrences in section_occurrences.items()
                if len(occurrences) > 1
            ]
            if duplicate_sections:
                issues.append(
                    Issue(
                        "ERROR",
                        "EXECUTABLE_CONTRACT_DUPLICATE",
                        f"{card_id} está {card.get('status')} com seção(ões) "
                        "duplicada(s): " + ", ".join(duplicate_sections),
                    )
                )
            sections = {
                heading: occurrences[0] if occurrences else None
                for heading, occurrences in section_occurrences.items()
            }
            empty_sections = [
                heading
                for heading, lines in sections.items()
                if lines is not None and not has_meaningful_markdown_content(lines)
            ]
            if empty_sections:
                issues.append(
                    Issue(
                        "ERROR",
                        "EXECUTABLE_CONTRACT_EMPTY",
                        f"{card_id} está {card.get('status')} com seção(ões) vazia(s): "
                        + ", ".join(empty_sections),
                    )
                )
            dor_lines = sections["Definition of Ready"]
            if dor_lines is not None:
                task_lines = [
                    line for line in dor_lines if TASK_PREFIX_PATTERN.match(line)
                ]
                checklist = [CHECKBOX_PATTERN.match(line) for line in task_lines]
                invalid_tasks = [
                    line
                    for line, match in zip(task_lines, checklist)
                    if match is None
                ]
                valid_checklist = [match for match in checklist if match is not None]
                if not task_lines:
                    issues.append(
                        Issue(
                            "ERROR",
                            "EXECUTABLE_DOR_CHECKLIST",
                            f"{card_id} está {card.get('status')} sem checklist "
                            "na Definition of Ready",
                        )
                    )
                elif invalid_tasks:
                    issues.append(
                        Issue(
                            "ERROR",
                            "EXECUTABLE_DOR_INVALID",
                            f"{card_id} está {card.get('status')} com item de DoR "
                            "malformado ou sem descrição",
                        )
                    )
                elif any(match.group(1) == " " for match in valid_checklist):
                    issues.append(
                        Issue(
                            "ERROR",
                            "EXECUTABLE_DOR_PENDING",
                            f"{card_id} está {card.get('status')} com item pendente "
                            "na Definition of Ready",
                        )
                    )
        if card.get("status") == "done":
            commits = card.get("commits")
            commit_shas: list[str] = []
            if not commits:
                issues.append(
                    Issue(
                        "ERROR",
                        "DONE_WITHOUT_COMMIT",
                        f"{card_id} está done sem commit registrado",
                    )
                )
            elif not isinstance(commits, list) or not all(
                isinstance(commit, str) and bool(commit.strip()) for commit in commits
            ):
                issues.append(
                    Issue(
                        "ERROR",
                        "DONE_COMMIT_TYPE",
                        f"{card_id}.commits deve ser uma lista de refs não vazias",
                    )
                )
            else:
                invalid_commits: list[str] = []
                for commit in commits:
                    match = FULL_COMMIT_REF_PATTERN.fullmatch(commit)
                    if match is None:
                        invalid_commits.append(commit)
                    else:
                        commit_shas.append(match.group("sha"))
                if invalid_commits:
                    issues.append(
                        Issue(
                            "ERROR",
                            "DONE_COMMIT_FORMAT",
                            f"{card_id} usa refs que não terminam em SHA completo: "
                            + ", ".join(invalid_commits),
                        )
                    )

            if card_content is not None:
                criteria_sections = markdown_sections(card_content, "Critérios")
                if len(criteria_sections) != 1:
                    issues.append(
                        Issue(
                            "ERROR",
                            "DONE_ACCEPTANCE_SECTION",
                            f"{card_id} deve ter exatamente uma seção Critérios de aceite",
                        )
                    )
                else:
                    criteria_lines = criteria_sections[0]
                    criteria_tasks = [
                        CHECKBOX_PATTERN.match(line)
                        for line in criteria_lines
                        if TASK_PREFIX_PATTERN.match(line)
                    ]
                    if not criteria_tasks:
                        issues.append(
                            Issue(
                                "ERROR",
                                "DONE_ACCEPTANCE_CHECKLIST",
                                f"{card_id} está done sem checklist de aceite",
                            )
                        )
                    elif any(match is None for match in criteria_tasks):
                        issues.append(
                            Issue(
                                "ERROR",
                                "DONE_ACCEPTANCE_INVALID",
                                f"{card_id} tem critério de aceite malformado ou vazio",
                            )
                        )
                    elif any(
                        match.group(1) == " " for match in criteria_tasks if match
                    ):
                        issues.append(
                            Issue(
                                "ERROR",
                                "DONE_ACCEPTANCE_PENDING",
                                f"{card_id} está done com critério de aceite pendente",
                            )
                        )

                all_tasks = markdown_task_matches(card_content)
                if any(
                    match is not None and match.group(1) == " "
                    for match in all_tasks
                ):
                    issues.append(
                        Issue(
                            "ERROR",
                            "DONE_CHECKLIST_PENDING",
                            f"{card_id} está done com checkbox pendente no card",
                        )
                    )
            evidence = card.get("evidence")
            if not evidence:
                issues.append(
                    Issue(
                        "ERROR",
                        "DONE_WITHOUT_EVIDENCE",
                        f"{card_id} está done sem evidência registrada",
                    )
                )
            elif not isinstance(evidence, list) or not all(
                isinstance(item, str) and item for item in evidence
            ):
                issues.append(
                    Issue(
                        "ERROR",
                        "DONE_EVIDENCE_TYPE",
                        f"{card_id}.evidence deve ser uma lista de paths não vazios",
                    )
                )
            else:
                canonical_evidence = f"program/evidence/{card_id}.md"
                if canonical_evidence not in evidence:
                    issues.append(
                        Issue(
                            "ERROR",
                            "DONE_WITHOUT_CARD_EVIDENCE",
                            f"{card_id} está done sem a evidência canônica "
                            f"{canonical_evidence}",
                        )
                    )
                else:
                    canonical_path = root / canonical_evidence
                    if not canonical_path.is_file():
                        issues.append(
                            Issue(
                                "ERROR",
                                "DONE_CARD_EVIDENCE_MISSING",
                                f"{card_id} aponta para evidência canônica ausente: "
                                f"{canonical_evidence}",
                            )
                        )
                    else:
                        try:
                            canonical_content = canonical_path.read_text(
                                encoding="utf-8"
                            )
                        except (OSError, UnicodeError) as error:
                            issues.append(
                                Issue(
                                    "ERROR",
                                    "DONE_CARD_EVIDENCE_UNREADABLE",
                                    f"{card_id} não consegue ler {canonical_evidence}: "
                                    f"{error}",
                                )
                            )
                        else:
                            if card_id not in canonical_content:
                                issues.append(
                                    Issue(
                                        "ERROR",
                                        "DONE_CARD_EVIDENCE_ID",
                                        f"{canonical_evidence} não contém o id "
                                        f"{card_id}",
                                    )
                                )
                            if len(canonical_content) < 500:
                                issues.append(
                                    Issue(
                                        "ERROR",
                                        "DONE_EVIDENCE_TOO_SHORT",
                                        f"{canonical_evidence} tem menos de 500 caracteres",
                                    )
                                )
                            if markdown_heading_count(canonical_content) < 3:
                                issues.append(
                                    Issue(
                                        "ERROR",
                                        "DONE_EVIDENCE_HEADINGS",
                                        f"{canonical_evidence} deve ter ao menos 3 headings",
                                    )
                                )
                            if EVIDENCE_DATE_PATTERN.search(canonical_content) is None:
                                issues.append(
                                    Issue(
                                        "ERROR",
                                        "DONE_EVIDENCE_DATE",
                                        f"{canonical_evidence} não registra data YYYY-MM-DD",
                                    )
                                )
                            if EVIDENCE_PASS_PATTERN.search(canonical_content) is None:
                                issues.append(
                                    Issue(
                                        "ERROR",
                                        "DONE_EVIDENCE_PASS",
                                        f"{canonical_evidence} não registra resultado PASS",
                                    )
                                )
                            if not commit_shas or not any(
                                sha in canonical_content for sha in commit_shas
                            ):
                                issues.append(
                                    Issue(
                                        "ERROR",
                                        "DONE_EVIDENCE_COMMIT_REF",
                                        f"{canonical_evidence} não cita um commit registrado",
                                    )
                                )
                            if not has_recorded_command(canonical_content):
                                issues.append(
                                    Issue(
                                        "ERROR",
                                        "DONE_EVIDENCE_COMMAND",
                                        f"{canonical_evidence} não registra comando executável",
                                    )
                                )
                            if EVIDENCE_SCOPE_PATTERN.search(canonical_content) is None:
                                issues.append(
                                    Issue(
                                        "ERROR",
                                        "DONE_EVIDENCE_SCOPE",
                                        f"{canonical_evidence} não registra limite, escopo ou rollback",
                                    )
                                )

    dependency_items = milestones + epics + cards
    dependency_ids = {
        item.get("id")
        for item in dependency_items
        if isinstance(item.get("id"), str)
    }
    graph: dict[str, list[str]] = {}
    for item in dependency_items:
        item_id = item.get("id")
        if not isinstance(item_id, str):
            continue
        dependencies = item.get("dependsOn", [])
        if not isinstance(dependencies, list):
            issues.append(
                Issue(
                    "ERROR",
                    "DEPENDENCY_TYPE",
                    f"{item_id}.dependsOn deve ser uma lista",
                )
            )
            continue
        graph[item_id] = [
            dependency for dependency in dependencies if isinstance(dependency, str)
        ]
        for dependency in dependencies:
            if dependency not in dependency_ids:
                issues.append(
                    Issue(
                        "ERROR",
                        "MISSING_DEPENDENCY",
                        f"{item_id} depende de id ausente: {dependency}",
                    )
                )
    for cycle in detect_cycles(graph):
        issues.append(
            Issue("ERROR", "DEPENDENCY_CYCLE", "ciclo: " + " -> ".join(cycle))
        )

    dependency_items_by_id = {
        item.get("id"): item
        for item in dependency_items
        if isinstance(item.get("id"), str)
    }
    for card in cards:
        if card.get("status") != "ready":
            continue
        for dependency in card.get("dependsOn", []):
            dependency_item = dependency_items_by_id.get(dependency)
            if dependency_item and dependency_item.get("status") != "done":
                issues.append(
                    Issue(
                        "ERROR",
                        "READY_DEPENDENCY",
                        f"{card.get('id')} está ready, mas {dependency} "
                        f"está {dependency_item.get('status')}",
                    )
                )

    active_cards = [card for card in cards if card.get("status") in ACTIVE_STATUSES]
    max_active = program.get("policy", {}).get("maxActiveCards", 1)
    if len(active_cards) > max_active:
        active_ids = ", ".join(card.get("id", "<sem-id>") for card in active_cards)
        issues.append(
            Issue(
                "ERROR",
                "WIP_LIMIT",
                f"{len(active_cards)} cards ativos excedem limite {max_active}: {active_ids}",
            )
        )

    pointer_values: dict[str, str | None] = {}
    pointer_validity: dict[str, bool] = {}
    for field in ("activeCardId", "nextCardId"):
        if field not in program:
            issues.append(
                Issue(
                    "ERROR",
                    "PROGRAM_POINTER_REQUIRED",
                    f"{field} deve existir e usar string ou null",
                )
            )
            pointer_values[field] = None
            pointer_validity[field] = False
            continue
        value = program[field]
        if value is not None and not isinstance(value, str):
            issues.append(
                Issue(
                    "ERROR",
                    "PROGRAM_POINTER_TYPE",
                    f"{field} deve usar string ou null",
                )
            )
            pointer_values[field] = None
            pointer_validity[field] = False
            continue
        pointer_values[field] = value
        pointer_validity[field] = True

    declared_active = pointer_values["activeCardId"]
    if active_cards:
        actual_active = active_cards[0].get("id") if len(active_cards) == 1 else None
        if pointer_validity["activeCardId"] and declared_active != actual_active:
            issues.append(
                Issue(
                    "ERROR",
                    "ACTIVE_CARD_MISMATCH",
                    f"activeCardId={declared_active}; ativo real={actual_active}",
                )
            )
    elif pointer_validity["activeCardId"] and declared_active is not None:
        issues.append(
            Issue(
                "ERROR",
                "ACTIVE_CARD_STALE",
                f"activeCardId={declared_active}, mas não há card ativo",
            )
        )

    next_card_id = pointer_values["nextCardId"]
    cards_by_id = {card.get("id"): card for card in cards}
    ready_cards = [card for card in cards if card.get("status") == "ready"]
    if not pointer_validity["nextCardId"]:
        pass
    elif active_cards:
        if next_card_id != declared_active:
            issues.append(
                Issue(
                    "ERROR",
                    "NEXT_ACTIVE_MISMATCH",
                    "enquanto há card ativo, nextCardId deve apontar para ele",
                )
            )
    elif next_card_id is None:
        if ready_cards:
            ready_ids = ", ".join(
                card.get("id", "<sem-id>") for card in ready_cards
            )
            issues.append(
                Issue(
                    "ERROR",
                    "NEXT_REQUIRED",
                    "há card(s) ready sem nextCardId selecionado: " + ready_ids,
                )
            )
    elif next_card_id not in cards_by_id:
        issues.append(
            Issue(
                "ERROR",
                "NEXT_CARD",
                f"nextCardId referencia card ausente: {next_card_id}",
            )
        )
    elif cards_by_id[next_card_id].get("status") != "ready":
        issues.append(
            Issue(
                "ERROR",
                "NEXT_NOT_READY",
                f"nextCardId={next_card_id} não está ready",
            )
        )

    for repository in repositories:
        repository_id = repository.get("id", "<sem-id>")
        if not valid_repository_layout(repository, root):
            issues.append(Issue("ERROR", "REPOSITORY_LAYOUT", f"{repository_id}: moduleRoot/path deve pertencer a repositoryRoot no workspace"))
            continue
        path = module_root(repository, root)
        if repository_id not in deferred_repositories and not path.is_dir():
            issues.append(
                Issue(
                    "ERROR",
                    "REPOSITORY_PATH",
                    f"{repository_id} aponta para diretório ausente: {path}",
                )
            )
        for field in ("cardGate", "ciGate"):
            if not repository.get(field):
                issues.append(
                    Issue(
                        "ERROR",
                        "REPOSITORY_GATE",
                        f"{repository_id} não declara {field}",
                    )
                )

    issues.extend(validate_adr005_acceptance(program, root))
    return issues


def validate_harness(
    program: dict[str, Any],
    repositories_doc: dict[str, Any],
    harness: dict[str, Any],
    harness_status: dict[str, Any],
) -> list[Issue]:
    issues: list[Issue] = []
    canonical = {
        repository["id"]: repository
        for repository in repositories_doc.get("repositories", [])
    }
    harness_repositories = {
        repository.get("name"): repository for repository in harness.get("repos", [])
    }

    missing = sorted(set(canonical) - set(harness_repositories))
    extra = sorted(set(harness_repositories) - set(canonical))
    if missing:
        issues.append(
            Issue(
                "ERROR",
                "HARNESS_REPOSITORIES",
                "repositórios ausentes no harness: " + ", ".join(missing),
            )
        )
    if extra:
        issues.append(
            Issue(
                "ERROR",
                "HARNESS_REPOSITORIES",
                "repositórios extras no harness: " + ", ".join(extra),
            )
        )

    for repository_id, canonical_repository in canonical.items():
        harness_repository = harness_repositories.get(repository_id)
        if not harness_repository:
            continue
        if harness_repository.get("path") != canonical_repository.get("path"):
            issues.append(
                Issue(
                    "ERROR",
                    "HARNESS_PATH",
                    f"{repository_id}: path do harness diverge do canônico",
                )
            )
        commands = harness_repository.get("commands", [])
        for field in ("cardGate", "ciGate"):
            command = canonical_repository.get(field)
            if command and command not in commands:
                issues.append(
                    Issue(
                        "ERROR",
                        "HARNESS_GATE",
                        f"{repository_id}: {field} ausente nos commands do harness",
                    )
                )

    program_active = program.get("activeCardId")
    harness_active = harness_status.get("active_card")
    if program_active != harness_active:
        issues.append(
            Issue(
                "ERROR",
                "HARNESS_ACTIVE_CARD",
                f"programa={program_active}; harness={harness_active}",
            )
        )

    required_agent_files = {"AGENTS.md", "program/README.md"} | {
        str(Path(repository.get("moduleRoot", repository.get("path", "."))) / "AGENTS.md")
        for repository in canonical.values()
    }
    missing_agent_files = sorted(
        required_agent_files - set(harness.get("agent_files", []))
    )
    if missing_agent_files:
        issues.append(
            Issue(
                "ERROR",
                "HARNESS_AGENT_FILES",
                "agent_files ausentes: " + ", ".join(missing_agent_files),
            )
        )
    return issues


def validate_dashboard(
    program: dict[str, Any], root: Path = ROOT, workspace: str | None = None
) -> list[Issue]:
    dashboard_path = root / ".dev-harness" / "dashboard.md"
    if not dashboard_path.is_file():
        return [
            Issue(
                "ERROR",
                "DASHBOARD_MISSING",
                ".dev-harness/dashboard.md não existe",
            )
        ]
    content = dashboard_path.read_text(encoding="utf-8")
    expected_fragments = [
        DASHBOARD_MARKER,
        f"Active card: `{program.get('activeCardId')}`",
        f"Pilot: `{program.get('productDecision', {}).get('pilot')}`",
        f"Production: `{program.get('productDecision', {}).get('production')}`",
        f"Workspace: `{workspace or 'full'}`",
    ]
    missing = [fragment for fragment in expected_fragments if fragment not in content]
    if missing:
        command = "python3 scripts/program_control.py dashboard"
        if workspace:
            command += f" --workspace {workspace}"
        return [
            Issue(
                "ERROR",
                "DASHBOARD_STALE",
                "dashboard foi sobrescrito ou não reflete o programa; "
                f"execute `{command}`",
            )
        ]
    return []


def validate_runtime(
    program: dict[str, Any], repositories_doc: dict[str, Any], root: Path = ROOT,
    *,
    deferred_repositories: frozenset[str] = frozenset(),
) -> list[Issue]:
    issues: list[Issue] = []
    cards_by_id = {card.get("id"): card for card in program.get("cards", [])}
    active_card = cards_by_id.get(optional_card_pointer(program, "activeCardId"))

    for repository in repositories_doc.get("repositories", []):
        repository_id = repository["id"]
        if repository_id in deferred_repositories:
            issues.append(
                Issue(
                    "WARN", "WORKSPACE_DEFERRED",
                    f"{repository_id}: adiado neste workspace; "
                    "Git e gates do módulo não avaliados",
                )
            )
            continue
        if not valid_repository_layout(repository, root):
            issues.append(Issue("ERROR", "REPOSITORY_LAYOUT", f"{repository_id}: raízes inválidas; Git não avaliado"))
            continue
        repo_path = repository_root(repository, root)
        return_code, inside = git_output(repo_path, "rev-parse", "--is-inside-work-tree")
        top_code, top = git_output(repo_path, "rev-parse", "--show-toplevel")
        if (
            return_code != 0 or inside != "true" or top_code != 0
            or Path(top).resolve() != repo_path.resolve()
        ):
            issues.append(
                Issue(
                    "ERROR",
                    "NOT_GIT_REPOSITORY",
                    f"{repository_id}: {repo_path} não é repositório Git",
                )
            )
            continue

        _, branch = git_output(repo_path, "branch", "--show-current")
        _, head = git_output(repo_path, "rev-parse", "HEAD")
        baseline = repository.get("baseline", {})
        if branch != baseline.get("branch"):
            issues.append(
                Issue(
                    "WARN",
                    "BRANCH_DRIFT",
                    f"{repository_id}: branch atual {branch}; baseline {baseline.get('branch')}",
                )
            )
        if head != baseline.get("sha"):
            issues.append(
                Issue(
                    "WARN",
                    "HEAD_DRIFT",
                    f"{repository_id}: HEAD atual {head}; baseline {baseline.get('sha')}",
                )
            )
        if not baseline.get("remoteEvidence", False):
            issues.append(
                Issue(
                    "WARN",
                    "NO_REMOTE_EVIDENCE",
                    f"{repository_id}: baseline local sem prova de CI remoto",
                )
            )

        _, dirty_output = git_output(
            repo_path, "status", "--porcelain=v1", "-z", "--untracked-files=all"
        )
        dirty_paths = module_dirty_paths(dirty_output, repository, repositories_doc.get("repositories", []), root)
        known_rules = repository.get("knownDirtyPaths", [])
        active_rules: list[str] = []
        if active_card and repository_id in active_card.get("repositories", []):
            active_rules = active_card.get("allowedDirtyPaths", {}).get(
                repository_id, []
            )
        elif not active_card and repository_id == "coordination":
            # Lifecycle bookkeeping happens between the completion of one card
            # and activation of the next. Only canonical state, card evidence
            # and its generated dashboard may change while the program is idle.
            active_rules = IDLE_CONTROL_PATHS

        known_matches: dict[str, list[str]] = {rule: [] for rule in known_rules}
        for dirty_path in dirty_paths:
            if any(path_matches(dirty_path, rule) for rule in active_rules):
                continue
            matching_rule = next(
                (rule for rule in known_rules if path_matches(dirty_path, rule)),
                None,
            )
            if matching_rule:
                known_matches[matching_rule].append(dirty_path)
                continue
            issues.append(
                Issue(
                    "ERROR",
                    "UNSCOPED_DIRTY_PATH",
                    f"{repository_id}: alteração fora do card ativo: {dirty_path}",
                )
            )
        for rule, matched_paths in known_matches.items():
            if not matched_paths:
                continue
            issues.append(
                Issue(
                    "WARN",
                    "KNOWN_DIRTY_PATH",
                    f"{repository_id}: {rule} preservado "
                    f"({len(matched_paths)} alteração(ões) preexistentes)",
                )
            )
    return issues


def collect_issues(
    root: Path = ROOT, *, check_dashboard: bool = True, workspace: str | None = None
) -> tuple[list[Issue], dict[str, Any], dict[str, Any]]:
    program = load_json(root / "program" / "program.json")
    repositories = load_json(root / "program" / "repositories.json")
    portable_harness = root / "workspaces" / "harness.json"
    harness = load_json(portable_harness if portable_harness.is_file()
                        else root / ".dev-harness" / "harness.json")
    harness_status = load_json(root / ".dev-harness" / "status.json")

    deferred = load_workspace(workspace, repositories, root)
    issues = validate_static(program, repositories, root, deferred_repositories=deferred)
    issues.extend(validate_harness(program, repositories, harness, harness_status))
    issues.extend(validate_runtime(
        program, repositories, root, deferred_repositories=deferred
    ))
    if check_dashboard:
        issues.extend(validate_dashboard(program, root, workspace))
    return issues, program, repositories


def print_issues(issues: list[Issue]) -> None:
    for issue in sorted(issues, key=lambda item: (item.level != "ERROR", item.code)):
        print(f"[{issue.level}] {issue.code}: {issue.message}")


def command_check(workspace: str | None = None) -> int:
    try:
        issues, program, _ = collect_issues(workspace=workspace)
    except ValueError as exc:
        print(f"[ERROR] LOAD: {exc}")
        return 1
    print(f"Workspace: {workspace or 'full'}; validação do controle, não dos runtimes ou da release.")
    print_issues(issues)
    errors = [issue for issue in issues if issue.level == "ERROR"]
    warnings = [issue for issue in issues if issue.level == "WARN"]
    if errors:
        print(
            f"Program check: FAIL ({len(errors)} erro(s), {len(warnings)} aviso(s))"
        )
        return 1
    print(
        f"Program check: PASS ({len(warnings)} aviso(s)); "
        f"active={program.get('activeCardId')}"
    )
    return 0


def command_summary(workspace: str | None = None) -> int:
    try:
        issues, program, repositories_doc = collect_issues(workspace=workspace)
        deferred = load_workspace(workspace, repositories_doc)
    except ValueError as exc:
        print(f"[ERROR] LOAD: {exc}")
        return 1

    counts = Counter(card.get("status") for card in program.get("cards", []))
    milestone_summary = ", ".join(
        f"{item['id']}={item['status']}" for item in program.get("milestones", [])
    )
    print(f"VanRides program — updated {program.get('updatedAt')}")
    print(f"Workspace: {workspace or 'full'}")
    print(
        f"Pilot={program.get('productDecision', {}).get('pilot')} | "
        f"Production={program.get('productDecision', {}).get('production')}"
    )
    print(
        f"Active={program.get('activeCardId')} | Next={program.get('nextCardId')}"
    )
    print("Cards: " + ", ".join(f"{key}={value}" for key, value in sorted(counts.items())))
    print("Milestones: " + milestone_summary)
    print("Repositories:")
    for repository in repositories_doc.get("repositories", []):
        if repository["id"] in deferred:
            print(f"- {repository['id']}: adiado; não avaliado neste workspace")
            continue
        repo_path = repository_root(repository, ROOT)
        _, branch = git_output(repo_path, "branch", "--show-current")
        _, head = git_output(repo_path, "rev-parse", "--short=12", "HEAD")
        _, dirty = git_output(
            repo_path, "status", "--porcelain=v1", "-z", "--untracked-files=all"
        )
        print(
            f"- {repository['id']}: {branch}@{head}; "
            f"module={repository.get('moduleRoot', repository['path'])}; "
            f"dirty={len(module_dirty_paths(dirty, repository, repositories_doc.get('repositories', []), ROOT))}; "
            f"remoteEvidence={repository.get('baseline', {}).get('remoteEvidence', False)}"
        )
    errors = sum(issue.level == "ERROR" for issue in issues)
    warnings = sum(issue.level == "WARN" for issue in issues)
    print(f"Control: errors={errors}; warnings={warnings}")
    return 1 if errors else 0


def command_next(root: Path | None = None, workspace: str | None = None) -> int:
    validation_root = ROOT if root is None else root
    program_path = PROGRAM_PATH if root is None else root / "program" / "program.json"
    repositories_path = (
        REPOSITORIES_PATH
        if root is None
        else root / "program" / "repositories.json"
    )
    try:
        program = load_json(program_path)
        repositories_doc = load_json(repositories_path)
        deferred = load_workspace(workspace, repositories_doc, validation_root)
    except ValueError as exc:
        print(f"[ERROR] LOAD: {exc}")
        return 1
    errors = [
        issue
        for issue in validate_static(
            program, repositories_doc, validation_root, deferred_repositories=deferred
        )
        if issue.level == "ERROR"
    ]
    if errors:
        for issue in errors:
            print(f"[{issue.level}] {issue.code}: {issue.message}")
        return 1
    card_id = program["activeCardId"] or program["nextCardId"]
    if card_id is None:
        executable = [
            card
            for card in program.get("cards", [])
            if card.get("status") in ACTIVE_STATUSES or card.get("status") == "ready"
        ]
        if executable:
            executable_ids = ", ".join(
                card.get("id", "<sem-id>") for card in executable
            )
            print(
                "[ERROR] NEXT_REQUIRED: há card executável sem seleção canônica: "
                + executable_ids
            )
            return 1
        print(
            "Nenhum card executável selecionado: não há card ativo nem ready; "
            "activeCardId e nextCardId permanecem null."
        )
        return 0
    card = next(
        (item for item in program.get("cards", []) if item.get("id") == card_id),
        None,
    )
    if not card:
        print(f"[ERROR] NEXT_CARD: card não encontrado: {card_id}")
        return 1
    print(f"{card['id']} [{card['status']}] — {card['title']}")
    print(card["cardFile"])
    if card.get("blockers"):
        print("Blockers:")
        for blocker in card["blockers"]:
            print(f"- {blocker}")
    return 0


def initialize_local_status(root: Path = ROOT) -> None:
    """Bootstrap the ignored projection without overwriting an existing harness."""
    path = root / ".dev-harness" / "status.json"
    if path.exists():
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    program = load_json(root / "program" / "program.json")
    with path.open("x", encoding="utf-8") as handle:
        json.dump({
            "active_card": program.get("activeCardId"),
            "source": "program/program.json",
            "note": "Projeção inicial; não é evidência de execução do harness externo.",
        }, handle, ensure_ascii=False, indent=2)
        handle.write("\n")


def command_dashboard(workspace: str | None = None) -> int:
    try:
        # Validate the requested profile before creating any local projection.
        repositories_doc = load_json(REPOSITORIES_PATH)
        deferred = load_workspace(workspace, repositories_doc)
        initialize_local_status()
        issues, program, repositories_doc = collect_issues(
            check_dashboard=False, workspace=workspace
        )
    except ValueError as exc:
        print(f"[ERROR] LOAD: {exc}")
        return 1

    errors = [issue for issue in issues if issue.level == "ERROR"]
    warnings = [issue for issue in issues if issue.level == "WARN"]
    cards = program.get("cards", [])
    card_counts = Counter(card.get("status") for card in cards)
    next_card_id = program.get("activeCardId") or program.get("nextCardId")
    next_card = next(
        (card for card in cards if card.get("id") == next_card_id),
        None,
    )

    lines = [
        "# VanRides Production Dashboard",
        "",
        f"> {DASHBOARD_MARKER}",
        "",
        f"- Workspace: `{workspace or 'full'}`",
        "- Scope: program control; module runtimes and release readiness are separate.",
        "",
        "## Release decision",
        "",
        f"- Pilot: `{program.get('productDecision', {}).get('pilot')}`",
        f"- Production: `{program.get('productDecision', {}).get('production')}`",
        f"- Reason: {program.get('productDecision', {}).get('reason')}",
        "",
        "## Active work",
        "",
        f"- Active card: `{program.get('activeCardId')}`",
        f"- Next card: `{program.get('nextCardId')}`",
        "- Global WIP: "
        f"`{sum(card.get('status') in ACTIVE_STATUSES for card in cards)}"
        f"/{program.get('policy', {}).get('maxActiveCards', 1)}`",
        "- Card states: "
        + ", ".join(
            f"`{status}={count}`" for status, count in sorted(card_counts.items())
        ),
        "",
        "## Quality gates",
        "",
        "| Gate | Name | Status |",
        "|---|---|---|",
    ]
    for milestone in program.get("milestones", []):
        lines.append(
            f"| {milestone['id']} | {milestone['name']} | "
            f"`{milestone['status']}` |"
        )

    lines.extend(
        [
            "",
            "## Repositories",
            "",
            "| Repository | Branch | Head | Dirty | Remote evidence |",
            "|---|---|---|---:|---|",
        ]
    )
    for repository in repositories_doc.get("repositories", []):
        if repository["id"] in deferred:
            lines.append(f"| {repository['id']} | deferred | not evaluated | — | — |")
            continue
        repo_path = repository_root(repository, ROOT)
        _, branch = git_output(repo_path, "branch", "--show-current")
        _, head = git_output(repo_path, "rev-parse", "--short=12", "HEAD")
        _, dirty = git_output(
            repo_path, "status", "--porcelain=v1", "-z", "--untracked-files=all"
        )
        remote_evidence = repository.get("baseline", {}).get(
            "remoteEvidence", False
        )
        lines.append(
            f"| {repository['id']} | `{branch}` | `{head}` | "
            f"{len(module_dirty_paths(dirty, repository, repositories_doc.get('repositories', []), ROOT))} | `{remote_evidence}` |"
        )

    lines.extend(
        [
            "",
            "## Program control",
            "",
            f"- Errors: `{len(errors)}`",
            f"- Warnings: `{len(warnings)}`",
        ]
    )
    if issues:
        lines.extend(["", "### Current issues", ""])
        for issue in sorted(
            issues, key=lambda item: (item.level != "ERROR", item.code, item.message)
        ):
            lines.append(f"- **{issue.level} {issue.code}:** {issue.message}")
    else:
        lines.extend(["", "- PASS: no issues found."])

    lines.extend(["", "## Next required action", ""])
    if errors:
        lines.append(
            "- Resolve control errors before implementation or card completion."
        )
    elif next_card:
        lines.append(
            f"- Continue `{next_card['id']}`: {next_card['title']} "
            f"([card](../{next_card['cardFile']}))."
        )
    else:
        lines.append("- No executable card selected.")
    lines.extend(
        [
            "",
            "This dashboard is a projection. Canonical state remains in "
            "`program/program.json`.",
            "",
        ]
    )

    DASHBOARD_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Dashboard written: {DASHBOARD_PATH}")
    return 1 if errors else 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "command",
        choices=("check", "summary", "next", "dashboard"),
        help="ação de controle",
    )
    parser.add_argument(
        "--workspace", metavar="NAME",
        help="perfil explícito em workspaces/NAME.json; sem opção, exige todos os módulos",
    )
    return parser


def main() -> int:
    args = build_parser().parse_args()
    if args.command == "check":
        return command_check(args.workspace)
    if args.command == "summary":
        return command_summary(args.workspace)
    if args.command == "dashboard":
        return command_dashboard(args.workspace)
    return command_next(workspace=args.workspace)


if __name__ == "__main__":
    sys.exit(main())
