def display_path(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def load_json(path: Path) -> dict[str, Any]:
    try:
        with path.open(encoding="utf-8") as handle:
            data = json.load(handle)
    except FileNotFoundError as exc:
        raise ValueError(f"arquivo ausente: {display_path(path)}") from exc
    except json.JSONDecodeError as exc:
        raise ValueError(
            f"JSON inválido em {display_path(path)}:{exc.lineno}:{exc.colno}: "
            f"{exc.msg}"
        ) from exc
    if not isinstance(data, dict):
        raise ValueError(f"objeto JSON esperado em {display_path(path)}")
    return data


def load_workspace(
    name: str | None, repositories: dict[str, Any], root: Path = ROOT
) -> frozenset[str]:
    """Return explicitly deferred repositories; no profile means full validation."""
    if name is None:
        return frozenset()
    if not re.fullmatch(r"[a-z][a-z0-9-]*", name):
        raise ValueError("nome de workspace inválido")
    profile = load_json(root / "workspaces" / f"{name}.json")
    included = profile.get("included")
    deferred = profile.get("deferred")
    if profile.get("schemaVersion") != 1 or profile.get("name") != name:
        raise ValueError("schema ou nome do workspace inválido")
    if (
        not isinstance(included, list)
        or not all(isinstance(item, str) for item in included)
        or len(included) != len(set(included))
        or "coordination" not in included
        or not isinstance(deferred, dict)
        or not all(
            isinstance(reason, str) and reason.strip() for reason in deferred.values()
        )
    ):
        raise ValueError(
            "workspace exige included único com coordination e razões em deferred"
        )
    ids = {repository["id"] for repository in repositories.get("repositories", [])}
    if set(included) & set(deferred) or set(included) | set(deferred) != ids:
        raise ValueError(
            "workspace deve classificar cada repositório canônico exatamente uma vez"
        )
    return frozenset(deferred)


def duplicates(values: Iterable[str]) -> list[str]:
    counts = Counter(values)
    return sorted(value for value, count in counts.items() if count > 1)


def path_matches(path: str, rule: str) -> bool:
    normalized_path = path.rstrip("/")
    normalized_rule = rule.rstrip("/")
    if normalized_rule in {".", "./"}:
        return True
    return normalized_path == normalized_rule or normalized_path.startswith(
        normalized_rule + "/"
    )


def repository_root(repository: dict[str, Any], root: Path) -> Path:
    """Git identity; legacy independent checkouts retain their original path."""
    return root / repository.get("repositoryRoot", repository.get("path", ""))


def module_root(repository: dict[str, Any], root: Path) -> Path:
    """Directory in which the module's own gates and relative rules run."""
    return root / repository.get("moduleRoot", repository.get("path", ""))


def valid_repository_layout(repository: dict[str, Any], root: Path) -> bool:
    declared = [repository.get(field, repository.get("path", ""))
                for field in ("repositoryRoot", "moduleRoot")]
    if any(not isinstance(value, str) or not value or Path(value).is_absolute()
           or ".." in Path(value).parts for value in declared):
        return False
    git_root = repository_root(repository, root).resolve()
    own_root = module_root(repository, root).resolve()
    return (git_root.is_relative_to(root.resolve())
            and own_root.is_relative_to(git_root)
            and ("moduleRoot" not in repository
                 or repository.get("path") == repository["moduleRoot"]))


def module_dirty_paths(
    output: str, repository: dict[str, Any], repositories: list[dict[str, Any]],
    root: Path,
) -> list[str]:
    """Partition shared Git changes without hiding paths outside any child module."""
    git_root = repository_root(repository, root).resolve()
    own_root = module_root(repository, root).resolve()
    own_prefix = own_root.relative_to(git_root).as_posix()
    children = [
        module_root(other, root).resolve().relative_to(git_root).as_posix()
        for other in repositories
        if other is not repository
        and valid_repository_layout(other, root)
        and repository_root(other, root).resolve() == git_root
        and module_root(other, root).resolve() != own_root
        and own_root in module_root(other, root).resolve().parents
    ]
    paths = []
    for path in parse_dirty_paths(output):
        if any(path_matches(path, prefix) for prefix in children):
            continue
        if own_prefix != ".":
            if not path_matches(path, own_prefix):
                continue
            path = path[len(own_prefix):].lstrip("/")
        paths.append(path)
    return paths


