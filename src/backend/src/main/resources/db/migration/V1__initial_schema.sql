CREATE TABLE motorista (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    telefone VARCHAR(255) NOT NULL,
    senha VARCHAR(255) NOT NULL,
    CONSTRAINT uk_motorista_email UNIQUE (email)
);

CREATE TABLE passageiro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    telefone VARCHAR(255) NOT NULL,
    senha VARCHAR(255) NOT NULL,
    endereco VARCHAR(255) NOT NULL,
    bairro VARCHAR(255) NOT NULL,
    cidade VARCHAR(255) NOT NULL,
    estado VARCHAR(255) NOT NULL,
    cep VARCHAR(255) NOT NULL,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    motorista_id BIGINT,
    CONSTRAINT uk_passageiro_email UNIQUE (email),
    CONSTRAINT fk_passageiro_motorista
        FOREIGN KEY (motorista_id) REFERENCES motorista (id)
);

CREATE TABLE presenca (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    passageiro_id BIGINT NOT NULL,
    data_presenca DATE NOT NULL,
    confirmado BOOLEAN NOT NULL,
    CONSTRAINT fk_presenca_passageiro
        FOREIGN KEY (passageiro_id) REFERENCES passageiro (id)
);

CREATE TABLE localizacao_motorista (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    data_hora TIMESTAMP(6),
    motorista_id BIGINT,
    CONSTRAINT fk_localizacao_motorista
        FOREIGN KEY (motorista_id) REFERENCES motorista (id)
);

CREATE TABLE refresh_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(128) NOT NULL,
    user_id BIGINT NOT NULL,
    user_role VARCHAR(32) NOT NULL,
    user_email VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    revoked BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_refresh_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_refresh_token_hash ON refresh_token (token_hash);
CREATE INDEX idx_refresh_token_user_id ON refresh_token (user_id);
