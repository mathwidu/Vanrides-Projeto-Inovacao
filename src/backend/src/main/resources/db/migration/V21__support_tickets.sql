CREATE TABLE support_ticket (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    created_by_passageiro_id BIGINT,
    created_by_guardian_id BIGINT,
    created_by_role VARCHAR(32) NOT NULL,
    created_by_user_id BIGINT NOT NULL,
    created_by_name VARCHAR(160) NOT NULL,
    category VARCHAR(64) NOT NULL,
    subject VARCHAR(160) NOT NULL,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    resolved_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_support_ticket_company
        FOREIGN KEY (company_id) REFERENCES company (id),
    CONSTRAINT fk_support_ticket_passageiro
        FOREIGN KEY (created_by_passageiro_id) REFERENCES passageiro (id),
    CONSTRAINT fk_support_ticket_guardian
        FOREIGN KEY (created_by_guardian_id) REFERENCES guardian (id)
);

CREATE INDEX idx_support_ticket_company_id ON support_ticket (company_id);
CREATE INDEX idx_support_ticket_company_status ON support_ticket (company_id, status);
CREATE INDEX idx_support_ticket_created_by
    ON support_ticket (company_id, created_by_role, created_by_user_id);
CREATE INDEX idx_support_ticket_updated_at ON support_ticket (updated_at);

CREATE TABLE support_ticket_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL,
    author_role VARCHAR(32) NOT NULL,
    author_user_id BIGINT NOT NULL,
    author_name VARCHAR(160) NOT NULL,
    message TEXT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_support_ticket_message_ticket
        FOREIGN KEY (ticket_id) REFERENCES support_ticket (id)
);

CREATE INDEX idx_support_ticket_message_ticket_id ON support_ticket_message (ticket_id);
CREATE INDEX idx_support_ticket_message_created_at ON support_ticket_message (created_at);
