    ADD COLUMN company_id BIGINT;

ALTER TABLE passageiro
    ADD COLUMN company_id BIGINT;

UPDATE motorista
SET company_id = (SELECT id FROM company WHERE slug = 'default')
WHERE company_id IS NULL;

UPDATE passageiro p
SET company_id = COALESCE(
    (SELECT m.company_id FROM motorista m WHERE m.id = p.motorista_id),
    (SELECT c.id FROM company c WHERE c.slug = 'default')
)
WHERE p.company_id IS NULL;

ALTER TABLE motorista
    ADD CONSTRAINT fk_motorista_company
        FOREIGN KEY (company_id) REFERENCES company (id);

ALTER TABLE passageiro
    ADD CONSTRAINT fk_passageiro_company
        FOREIGN KEY (company_id) REFERENCES company (id);

CREATE INDEX idx_motorista_company_id ON motorista (company_id);
CREATE INDEX idx_passageiro_company_id ON passageiro (company_id);
