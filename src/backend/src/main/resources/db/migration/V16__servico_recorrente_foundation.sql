CREATE TABLE servico_recorrente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    rota_base_id BIGINT,
    motorista_padrao_id BIGINT,
    nome VARCHAR(255) NOT NULL,
    tipo_operacao VARCHAR(32) NOT NULL DEFAULT 'IDA',
    horario_partida TIME,
    dias_operacao VARCHAR(255) NOT NULL DEFAULT 'MONDAY,TUESDAY,WEDNESDAY,THURSDAY,FRIDAY',
    destino_final_nome VARCHAR(255),
    destino_final_endereco VARCHAR(512),
    destino_final_latitude DOUBLE PRECISION,
    destino_final_longitude DOUBLE PRECISION,
    politica_presenca VARCHAR(32) NOT NULL DEFAULT 'INCLUIR_POR_PADRAO',
    capacidade_planejada INTEGER,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    geracao_automatica_ativa BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_servico_recorrente_company
        FOREIGN KEY (company_id) REFERENCES company (id),
    CONSTRAINT fk_servico_recorrente_rota_base
        FOREIGN KEY (rota_base_id) REFERENCES rota_base (id),
    CONSTRAINT fk_servico_recorrente_motorista_padrao
        FOREIGN KEY (motorista_padrao_id) REFERENCES motorista (id),
    CONSTRAINT uk_servico_recorrente_rota_base
        UNIQUE (rota_base_id)
);

CREATE TABLE servico_passageiro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    servico_recorrente_id BIGINT NOT NULL,
    passageiro_id BIGINT NOT NULL,
    ordem_padrao INTEGER,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    data_inicio DATE,
    data_fim DATE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_servico_passageiro_company
        FOREIGN KEY (company_id) REFERENCES company (id),
    CONSTRAINT fk_servico_passageiro_servico
        FOREIGN KEY (servico_recorrente_id) REFERENCES servico_recorrente (id) ON DELETE CASCADE,
    CONSTRAINT fk_servico_passageiro_passageiro
        FOREIGN KEY (passageiro_id) REFERENCES passageiro (id),
    CONSTRAINT uk_servico_passageiro
        UNIQUE (servico_recorrente_id, passageiro_id)
);

CREATE TABLE presenca_servico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    servico_recorrente_id BIGINT NOT NULL,
    passageiro_id BIGINT NOT NULL,
    presenca_id BIGINT,
    data_operacao DATE NOT NULL,
    status VARCHAR(32) NOT NULL,
    origem VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_presenca_servico_company
        FOREIGN KEY (company_id) REFERENCES company (id),
    CONSTRAINT fk_presenca_servico_servico
        FOREIGN KEY (servico_recorrente_id) REFERENCES servico_recorrente (id) ON DELETE CASCADE,
    CONSTRAINT fk_presenca_servico_passageiro
        FOREIGN KEY (passageiro_id) REFERENCES passageiro (id),
    CONSTRAINT fk_presenca_servico_presenca
        FOREIGN KEY (presenca_id) REFERENCES presenca (id),
    CONSTRAINT uk_presenca_servico
        UNIQUE (servico_recorrente_id, passageiro_id, data_operacao)
);

CREATE INDEX idx_servico_recorrente_company_id ON servico_recorrente (company_id);
CREATE INDEX idx_servico_recorrente_motorista_id ON servico_recorrente (motorista_padrao_id);
CREATE INDEX idx_servico_passageiro_company_id ON servico_passageiro (company_id);
CREATE INDEX idx_servico_passageiro_servico_id ON servico_passageiro (servico_recorrente_id);
CREATE INDEX idx_servico_passageiro_passageiro_id ON servico_passageiro (passageiro_id);
CREATE INDEX idx_presenca_servico_company_data ON presenca_servico (company_id, data_operacao);
CREATE INDEX idx_presenca_servico_passageiro_data ON presenca_servico (passageiro_id, data_operacao);
CREATE INDEX idx_presenca_servico_servico_data ON presenca_servico (servico_recorrente_id, data_operacao);

