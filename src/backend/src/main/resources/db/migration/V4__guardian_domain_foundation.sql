CREATE TABLE guardian (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    telefone VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_guardian_company
        FOREIGN KEY (company_id) REFERENCES company (id),
    CONSTRAINT uk_guardian_company_email
        UNIQUE (company_id, email)
);

CREATE INDEX idx_guardian_company_id ON guardian (company_id);
CREATE INDEX idx_guardian_company_email ON guardian (company_id, email);

CREATE TABLE guardian_passageiro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    guardian_id BIGINT NOT NULL,
    passageiro_id BIGINT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_guardian_passageiro_company
        FOREIGN KEY (company_id) REFERENCES company (id),
    CONSTRAINT fk_guardian_passageiro_guardian
        FOREIGN KEY (guardian_id) REFERENCES guardian (id),
    CONSTRAINT fk_guardian_passageiro_passageiro
        FOREIGN KEY (passageiro_id) REFERENCES passageiro (id),
    CONSTRAINT uk_guardian_passageiro
        UNIQUE (guardian_id, passageiro_id)
);

CREATE INDEX idx_guardian_passageiro_company_id ON guardian_passageiro (company_id);
CREATE INDEX idx_guardian_passageiro_guardian_id ON guardian_passageiro (guardian_id);
CREATE INDEX idx_guardian_passageiro_passageiro_id ON guardian_passageiro (passageiro_id);
