CREATE TABLE rota_base (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    motorista_id BIGINT NOT NULL,
    nome VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_rota_base_company
        FOREIGN KEY (company_id) REFERENCES company (id),
    CONSTRAINT fk_rota_base_motorista
        FOREIGN KEY (motorista_id) REFERENCES motorista (id)
);

CREATE TABLE rota_base_parada (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rota_base_id BIGINT NOT NULL,
    passageiro_id BIGINT NOT NULL,
    ordem INTEGER NOT NULL,
    CONSTRAINT fk_rota_base_parada_rota
        FOREIGN KEY (rota_base_id) REFERENCES rota_base (id) ON DELETE CASCADE,
    CONSTRAINT fk_rota_base_parada_passageiro
        FOREIGN KEY (passageiro_id) REFERENCES passageiro (id),
    CONSTRAINT uk_rota_base_parada_ordem
        UNIQUE (rota_base_id, ordem)
);

CREATE TABLE viagem (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    rota_base_id BIGINT NOT NULL,
    motorista_id BIGINT NOT NULL,
    data_operacao DATE NOT NULL,
    status VARCHAR(32) NOT NULL,
    CONSTRAINT fk_viagem_company
        FOREIGN KEY (company_id) REFERENCES company (id),
    CONSTRAINT fk_viagem_rota_base
        FOREIGN KEY (rota_base_id) REFERENCES rota_base (id),
    CONSTRAINT fk_viagem_motorista
        FOREIGN KEY (motorista_id) REFERENCES motorista (id),
    CONSTRAINT uk_viagem_rota_base_data
        UNIQUE (rota_base_id, data_operacao)
);

CREATE TABLE viagem_parada (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    viagem_id BIGINT NOT NULL,
    passageiro_id BIGINT NOT NULL,
    ordem INTEGER NOT NULL,
    status VARCHAR(32) NOT NULL,
    CONSTRAINT fk_viagem_parada_viagem
        FOREIGN KEY (viagem_id) REFERENCES viagem (id) ON DELETE CASCADE,
    CONSTRAINT fk_viagem_parada_passageiro
        FOREIGN KEY (passageiro_id) REFERENCES passageiro (id),
    CONSTRAINT uk_viagem_parada_ordem
        UNIQUE (viagem_id, ordem)
);

CREATE INDEX idx_rota_base_company_id ON rota_base (company_id);
CREATE INDEX idx_rota_base_motorista_id ON rota_base (motorista_id);
CREATE INDEX idx_rota_base_parada_rota_id ON rota_base_parada (rota_base_id);
CREATE INDEX idx_rota_base_parada_passageiro_id ON rota_base_parada (passageiro_id);
CREATE INDEX idx_viagem_company_data ON viagem (company_id, data_operacao);
CREATE INDEX idx_viagem_motorista_data ON viagem (motorista_id, data_operacao);
CREATE INDEX idx_viagem_parada_viagem_id ON viagem_parada (viagem_id);
CREATE INDEX idx_viagem_parada_passageiro_id ON viagem_parada (passageiro_id);
