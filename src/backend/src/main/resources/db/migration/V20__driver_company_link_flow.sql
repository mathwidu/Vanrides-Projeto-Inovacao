CREATE TABLE driver_company_membership (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    motorista_id BIGINT NOT NULL,
    company_id BIGINT NOT NULL,
    status VARCHAR(32) NOT NULL,
    source VARCHAR(32) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    activated_at TIMESTAMP(6) WITH TIME ZONE,
    suspended_at TIMESTAMP(6) WITH TIME ZONE,
    removed_at TIMESTAMP(6) WITH TIME ZONE,
    review_notes VARCHAR(255),
    CONSTRAINT fk_driver_company_membership_motorista
        FOREIGN KEY (motorista_id) REFERENCES motorista (id),
    CONSTRAINT fk_driver_company_membership_company
        FOREIGN KEY (company_id) REFERENCES company (id)
);

CREATE INDEX idx_driver_company_membership_motorista_id ON driver_company_membership (motorista_id);
CREATE INDEX idx_driver_company_membership_company_id ON driver_company_membership (company_id);
CREATE INDEX idx_driver_company_membership_status ON driver_company_membership (status);
CREATE UNIQUE INDEX uk_driver_company_membership_active_motorista
    ON driver_company_membership (motorista_id)
    WHERE status = 'ACTIVE';

CREATE TABLE driver_company_invite (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    created_by_company_admin_id BIGINT NOT NULL,
    accepted_by_motorista_id BIGINT,
    token_hash VARCHAR(128) NOT NULL,
    status VARCHAR(32) NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE,
    accepted_at TIMESTAMP(6) WITH TIME ZONE,
    cancelled_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_driver_company_invite_company
        FOREIGN KEY (company_id) REFERENCES company (id),
    CONSTRAINT fk_driver_company_invite_company_admin
        FOREIGN KEY (created_by_company_admin_id) REFERENCES company_admin (id),
    CONSTRAINT fk_driver_company_invite_motorista
        FOREIGN KEY (accepted_by_motorista_id) REFERENCES motorista (id),
    CONSTRAINT uk_driver_company_invite_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_driver_company_invite_company_id ON driver_company_invite (company_id);
CREATE INDEX idx_driver_company_invite_status ON driver_company_invite (status);
CREATE INDEX idx_driver_company_invite_expires_at ON driver_company_invite (expires_at);

CREATE TABLE driver_company_link_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    motorista_id BIGINT NOT NULL,
    company_id BIGINT NOT NULL,
    status VARCHAR(32) NOT NULL,
    requested_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    reviewed_at TIMESTAMP(6) WITH TIME ZONE,
    reviewed_by_company_admin_id BIGINT,
    review_notes VARCHAR(255),
    CONSTRAINT fk_driver_company_link_request_motorista
        FOREIGN KEY (motorista_id) REFERENCES motorista (id),
    CONSTRAINT fk_driver_company_link_request_company
        FOREIGN KEY (company_id) REFERENCES company (id),
    CONSTRAINT fk_driver_company_link_request_company_admin
        FOREIGN KEY (reviewed_by_company_admin_id) REFERENCES company_admin (id)
);

CREATE INDEX idx_driver_company_link_request_motorista_id ON driver_company_link_request (motorista_id);
CREATE INDEX idx_driver_company_link_request_company_id ON driver_company_link_request (company_id);
CREATE INDEX idx_driver_company_link_request_status ON driver_company_link_request (status);
CREATE UNIQUE INDEX uk_driver_company_link_request_pending_motorista
    ON driver_company_link_request (motorista_id)
    WHERE status = 'PENDING';
