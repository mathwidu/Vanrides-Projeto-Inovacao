CREATE TABLE notification_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(64) NOT NULL,
    recipient_role VARCHAR(32) NOT NULL,
    recipient_user_id BIGINT NOT NULL,
    company_id BIGINT,
    title VARCHAR(160) NOT NULL,
    body VARCHAR(500) NOT NULL,
    data_json TEXT,
    status VARCHAR(64) NOT NULL,
    attempts INTEGER NOT NULL,
    provider_status VARCHAR(160),
    dispatched_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_notification_event_recipient
    ON notification_event (recipient_role, recipient_user_id);
CREATE INDEX idx_notification_event_company_id ON notification_event (company_id);
CREATE INDEX idx_notification_event_status ON notification_event (status);
CREATE INDEX idx_notification_event_created_at ON notification_event (created_at);
