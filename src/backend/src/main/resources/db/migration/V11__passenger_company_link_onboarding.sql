CREATE TABLE company_link_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    passageiro_id BIGINT NOT NULL,
    company_id BIGINT NOT NULL,
    status VARCHAR(32) NOT NULL,
    source VARCHAR(32) NOT NULL,
    requested_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    reviewed_at TIMESTAMP(6) WITH TIME ZONE,
    reviewed_by_company_admin_id BIGINT,
    review_notes VARCHAR(255),
    CONSTRAINT fk_company_link_request_passageiro
        FOREIGN KEY (passageiro_id) REFERENCES passageiro (id),
    CONSTRAINT fk_company_link_request_company
        FOREIGN KEY (company_id) REFERENCES company (id),
    CONSTRAINT fk_company_link_request_company_admin
        FOREIGN KEY (reviewed_by_company_admin_id) REFERENCES company_admin (id)
);

CREATE INDEX idx_company_link_request_passageiro_id ON company_link_request (passageiro_id);
CREATE INDEX idx_company_link_request_company_id ON company_link_request (company_id);
CREATE INDEX idx_company_link_request_status ON company_link_request (status);
CREATE UNIQUE INDEX uk_company_link_request_pending_per_passageiro
    ON company_link_request (passageiro_id)
    WHERE status = 'PENDING';

CREATE TABLE company_invite_code (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    created_by_company_admin_id BIGINT NOT NULL,
    code VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL,
    max_uses INTEGER,
    use_count INTEGER NOT NULL DEFAULT 0,
    expires_at TIMESTAMP(6) WITH TIME ZONE,
    last_used_at TIMESTAMP(6) WITH TIME ZONE,
    cancelled_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_company_invite_code_company
        FOREIGN KEY (company_id) REFERENCES company (id),
    CONSTRAINT fk_company_invite_code_company_admin
        FOREIGN KEY (created_by_company_admin_id) REFERENCES company_admin (id),
    CONSTRAINT uk_company_invite_code_code UNIQUE (code)
);

CREATE INDEX idx_company_invite_code_company_id ON company_invite_code (company_id);
CREATE INDEX idx_company_invite_code_status ON company_invite_code (status);
CREATE INDEX idx_company_invite_code_expires_at ON company_invite_code (expires_at);

CREATE TABLE company_invite_code_usage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invite_code_id BIGINT NOT NULL,
    passageiro_id BIGINT NOT NULL,
    used_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_company_invite_code_usage_invite_code
        FOREIGN KEY (invite_code_id) REFERENCES company_invite_code (id),
    CONSTRAINT fk_company_invite_code_usage_passageiro
        FOREIGN KEY (passageiro_id) REFERENCES passageiro (id),
    CONSTRAINT uk_company_invite_code_usage UNIQUE (invite_code_id, passageiro_id)
);

CREATE INDEX idx_company_invite_code_usage_invite_code_id ON company_invite_code_usage (invite_code_id);
CREATE INDEX idx_company_invite_code_usage_passageiro_id ON company_invite_code_usage (passageiro_id);
