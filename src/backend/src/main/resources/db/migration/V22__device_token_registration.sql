CREATE TABLE device_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(128) NOT NULL,
    token_value VARCHAR(1024) NOT NULL,
    platform VARCHAR(32) NOT NULL,
    user_id BIGINT NOT NULL,
    user_role VARCHAR(32) NOT NULL,
    user_email VARCHAR(255),
    company_id BIGINT,
    active BOOLEAN NOT NULL,
    last_registered_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    invalidated_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_device_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_device_token_user ON device_token (user_role, user_id);
CREATE INDEX idx_device_token_company_id ON device_token (company_id);
CREATE INDEX idx_device_token_active ON device_token (active);
