import crypto from 'node:crypto';
import { demand, exact, localJson, privateBytes, privateWrite, properties, quote, summary, token, uuid } from './070-worker-common.mjs';
import { extractConfirmationMarker, extractPassengerInviteCode, successfulReceipt } from './080-driver-evidence.mjs';

/** Use the same authenticated inbound route as Evolution. Sensitive reply text stays in memory. */
export function passengerConversation({ input, tools, actor, address, peers, instance, credentials, worker, provider, interruption }) {
  const driver = { actor, address };
  const byActor = new Map([driver, ...peers].map(person => [person.actor, person]));
  const config = properties(privateBytes(input.configFile));
  const hashKey = Buffer.from(config.get('vanrides.wa.hash-key') ?? '', 'base64url');
  config.clear();
  demand(peers.length === 2 && byActor.size === 3 && hashKey.length === 32, 'PASSENGER_COHORT_INVALID');
  let lastEvent, lastReceipt, events = 0, duplicates = 0, deliveries = 0, peerDeliveries = 0, starts = 1;

  async function submit(event, expected = 'PERSISTED') {
    const response = await interruption.wait(() => localJson(input.state.api_base_url, '/integrations/whatsapp/v1/events', {
      method: 'POST', body: event, headers: { Authorization: 'Bearer ' + credentials[0].credential },
    }));
    demand(response.status === 202 && exact(response.data, ['receiptId', 'status', 'serverTime'])
      && response.data.status === expected && uuid(response.data.receiptId), 'PASSENGER_EVENT_NOT_DURABLE');
    return response.data.receiptId;
  }
  async function control(route, kind, status) {
    const response = await interruption.wait(() => worker.request(route));
    demand(response.status === 200, 'PASSENGER_CONTROL_HTTP_FAILED');
    summary(response.data, kind, status, response.status);
  }

  async function send(person, message, command, { notify, expectedError, verifyRunLink } = {}) {
    const id = 'wa090_' + crypto.randomUUID().replaceAll('-', '');
    lastEvent = { event: 'messages.upsert', instance, date_time: new Date().toISOString(), data: {
      key: { id, fromMe: false, remoteJid: person.address }, messageTimestamp: Math.floor(Date.now() / 1000),
      message: typeof message === 'string' ? { conversation: message } : message,
    } };
    lastReceipt = await submit(lastEvent); events++;
    await control('/v1/process-inbox', 'process', 'PROCESSED');
    const raw = tools.sql(`SELECT json_build_object('command',r.command_type,'result',r.result_json,'boxes',(
      SELECT json_agg(json_build_object('id',o.id,'actor',o.recipient_identity_id,'text',o.payload_json->>'text',
        'hash',i.code_hash) ORDER BY o.created_at,o.id) FROM wa.message_outbox o
        LEFT JOIN wa.driver_invite i ON i.id=o.private_invite_id WHERE o.command_id=r.command_id))
      FROM wa.command_receipt r WHERE r.inbox_event_id=${quote(lastReceipt)} AND r.identity_id=${quote(person.actor)};`, { recordOutput: false });
    demand(raw && !raw.includes('\n'), 'PASSENGER_SINGLE_COMMAND_REQUIRED');
    const result = JSON.parse(raw);
    privateWrite(tools.next('passenger-step.json'), JSON.stringify({ ordinal: events, expected: command,
      observed: result.command, outcome: result.result.outcome ?? result.result.errorCode,
      responseCount: result.boxes?.length ?? 0 }) + '\n');
    demand([command].flat().includes(result.command), 'PASSENGER_UNEXPECTED_COMMAND');
    demand(expectedError ? result.result.errorCode === expectedError : successfulReceipt(result.result), 'PASSENGER_UNEXPECTED_OUTCOME');
    const recipients = [person.actor, ...(notify ? [notify.actor] : [])].sort();
    const boxes = result.boxes;
    demand(Array.isArray(boxes) && boxes.length === recipients.length
      && boxes.map(box => box.actor).sort().every((id, i) => id === recipients[i]), 'PASSENGER_WRONG_RECIPIENTS');
    if (!expectedError) demand(Array.isArray(result.result.responseIds) && result.result.responseIds.length === boxes.length
      && boxes.every(box => uuid(box.id) && result.result.responseIds.includes(box.id)), 'PASSENGER_RECEIPT_MISSING_RESPONSE');
    const delivered = new Map();
    for (const box of boxes) {
      provider.enqueue({ outboxId: box.id, address: byActor.get(box.actor).address, matches: text => {
        if (verifyRunLink) {
          if (!['REQUEST_START','REQUEST_RESUME'].includes(result.command) || box.actor !== driver.actor
              || !verifyRunLink(text, box.text)) return false;
        } else if (box.hash) {
          const raw = extractPassengerInviteCode(text);
          if (!raw || result.command !== 'CREATE_INVITE' || crypto.createHmac('sha256', hashKey)
            .update('passenger-invite\0' + raw).digest('hex') !== box.hash) return false;
        } else {
          // A counterpart's map is generated by the API during authorize-submit.
          // Check the stored message and allow only the synthetic map suffix here.
          if (typeof box.text !== 'string' || !box.text.length || !text.startsWith(box.text)) return false;
          const suffix = text.slice(box.text.length).trim();
          if (suffix && !validTestMap(suffix)) return false;
        }
        delivered.set(box.actor, text); return true;
      } });
      await control('/v1/dispatch-one', 'dispatch', 'SUBMITTED'); deliveries++;
      const counts = provider.counts();
      demand(counts.requests === deliveries && counts.accepted === deliveries && counts.pending === 0 && counts.failures === 0,
        'PASSENGER_DISPATCH_NOT_VERIFIED');
      if (box.actor !== person.actor) peerDeliveries++;
    }
    return { reply: delivered.get(person.actor), peer: notify ? delivered.get(notify.actor) : null };
  }

  async function replay() {
    demand(await submit(lastEvent, 'DUPLICATE') === lastReceipt, 'PASSENGER_DUPLICATE_RECEIPT_CHANGED'); duplicates++;
    await control('/v1/process-inbox', 'process', 'IDLE'); await control('/v1/dispatch-one', 'dispatch', 'IDLE');
    demand(provider.counts().accepted === deliveries, 'PASSENGER_REPLAY_RESENT');
  }
  async function restart() {
    await interruption.wait(() => worker.stop()); await interruption.wait(() => worker.start()); starts++;
  }
  async function deliverReminder(person, box) {
    demand(byActor.get(person.actor)?.address === person.address && uuid(box.id) && typeof box.text === 'string'
      && box.text.includes('VOU') && box.text.includes('pendente'), 'ATTENDANCE_REMINDER_INVALID');
    provider.enqueue({ outboxId: box.id, address: person.address, text: box.text });
    await control('/v1/dispatch-one', 'dispatch', 'SUBMITTED'); deliveries++;
    demand(provider.counts().accepted === deliveries && provider.counts().failures === 0
      && provider.counts().pending === 0, 'ATTENDANCE_REMINDER_NOT_SUBMITTED');
  }
  // Autonomous outbox rows have no inbound command. Only consume an expected
  // synthetic recipient and match both the stored message and the provider submission.
  async function deliverRunNotice(person, box, expectedText) {
    demand(byActor.get(person.actor)?.address === person.address && uuid(box.id) && typeof box.text === 'string'
      && expectedText.test(box.text), 'RUN_NOTICE_TEXT_INVALID');
    provider.enqueue({ outboxId: box.id, address: person.address, text: box.text });
    await control('/v1/dispatch-one', 'dispatch', 'SUBMITTED'); deliveries++;
    demand(provider.counts().accepted === deliveries && provider.counts().failures === 0, 'RUN_NOTICE_DELIVERY_INVALID');
  }
  async function bootstrap(person, displayName) {
    await send(person, 'oi', 'START_ONBOARDING');
    interruption.assertActive();
    const invite = tools.operate('driver-bootstrap', { identityId: person.actor, expiresAt: new Date(Date.now() + 1800000).toISOString() });
    demand(token(invite.driverInviteCode), 'PASSENGER_TEST_BOOTSTRAP_INVALID');
    await send(person, invite.driverInviteCode, 'CLAIM_DRIVER_INVITE'); delete invite.driverInviteCode;
    await send(person, displayName, 'SET_PROFILE_NAME'); await send(person, 'ACEITO', 'ACCEPT_NOTICE');
  }
  const confirm = (person, offered, command, options) => {
    const marker = extractConfirmationMarker(offered.reply);
    demand(marker !== null, 'PASSENGER_REVIEW_MARKER_MISSING');
    return send(person, 'CONFIRMAR ' + marker, command, options);
  };
  return { send, confirm, bootstrap, restart, replay, deliverReminder, deliverRunNotice, driver, passenger: peers[0], otherDriver: peers[1],
    totals: () => ({ uniqueEvents: events, duplicateEvents: duplicates, commandReceipts: events,
      submittedAttempts: deliveries, providerRequests: deliveries, crossActorDeliveries: peerDeliveries, workerStarts: starts }),
    dispose: () => { hashKey.fill(0); lastEvent = null; } };
}

// Fixture coordinates are deliberately synthetic; map links from any other host or pin fail the smoke.
function validTestMap(suffix) {
  const matches = [...suffix.matchAll(/https:\/\/[^\s]+/gu)];
  if (matches.length !== 1 || suffix.replace(matches[0][0], '').trim().length > 55) return false;
  try {
    const url = new URL(matches[0][0]);
    return url.origin === 'https://www.google.com' && url.pathname === '/maps/search/' && url.searchParams.get('api') === '1'
      && /^0(?:\.0+)?,(?:0(?:\.0+)?|0\.0010*)$/u.test(url.searchParams.get('query') ?? '');
  } catch { return false; }
}
